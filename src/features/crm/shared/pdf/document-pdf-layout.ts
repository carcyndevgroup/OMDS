function drawTotalRow(page: PDFPage, font: any, xLabel: number, xValue: number, y: number, label: string, value: string) {
  page.drawText(label.toUpperCase(), { color: rgb(0.37, 0.4, 0.46), font, size: 9, x: xLabel, y });
  page.drawText(formatCurrency(value), { color: rgb(0.12, 0.14, 0.19), font, size: 9, x: xValue, y });
}

function trim(value: string, max: number) {
  if (value.length <= max) return value;
  return `${value.slice(0, max - 1)}...`;
}

function formatCurrency(value: string) {
  return new Intl.NumberFormat("en-US", { currency: "MXN", style: "currency" }).format(Number(value || 0));
}

function formatDate(value: string | null) {
  if (!value) return "Not provided";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "Not provided";
  return new Intl.DateTimeFormat("en-US", { dateStyle: "medium" }).format(date);
}

async function loadLogo(pdf: PDFDocument) {
  try {
    const logoPath = path.join(process.cwd(), "public", "branding", "ohmydesserts-logo-color.png");
    const file = await readFile(logoPath);
    return pdf.embedPng(file);
  } catch {
    return null;
  }
}
